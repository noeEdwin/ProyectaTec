export function correoValido(correo: string): boolean {
  if (!EMAIL_REGEX.test(correo)) return false;
  const dominio = correo.split('@')[1].toLowerCase();
  return DOMINIOS_PERMITIDOS.has(dominio);
}

// Traduce al español los errores de correo que llegan de la API en inglés
export function traducirErrorCorreo(mensaje?: string): string | undefined {
  if (!mensaje) return undefined;
  if (/already been taken/i.test(mensaje)) {
    return 'Este correo electrónico ya está registrado.';
  }
  return mensaje;
}